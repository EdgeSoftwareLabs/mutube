#!/usr/bin/env python3
"""Build YouTube + for the non-Apple platforms.

  python3 platforms/build_platforms.py web                 -> platforms/web/youtube-plus.user.js
  python3 platforms/build_platforms.py webos [--with-tizentube]
                                                           -> build/webos/  (then: ares-package build/webos -o build)
  python3 platforms/build_platforms.py tizen-module        -> platforms/tizen/module/dist/{userScript,service}.js
  python3 platforms/build_platforms.py tizen-standalone --tizentube-src /path/to/TizenTube
                                                           -> build/tizen-standalone/ (then: Tizen Studio / `tizen package -t wgt`)
  python3 platforms/build_platforms.py all

TizenTube (GPL-3.0, github.com/reisxd/TizenTube) is downloaded at build time at
TIZENTUBE_VERSION from jsDelivr; it is not vendored in this repo. Bundles that
include it must be distributed under GPL-3.0 terms.
"""
import argparse
import json
import re
import shutil
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAT = ROOT / "platforms"
BUILD = ROOT / "build"
YTPLUS = ROOT / "youtube-plus.js"
TIZENTUBE_VERSION = "1.15.2"
TT_NPM = f"https://cdn.jsdelivr.net/npm/@foxreis/tizentube@{TIZENTUBE_VERSION}"
TT_URL_RE = re.compile(r"https://cdn\.jsdelivr\.net/npm/@foxreis/tizentube/dist/userScript\.js")
# Where the Tizen module bundle is served from once the branch is pushed.
TIZEN_BUNDLE_URL = "https://cdn.jsdelivr.net/gh/mistermassacre/mutube@youtube-plus/platforms/tizen/module/dist/userScript.js"


def fetch(url):
    print("  fetching", url)
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def version():
    m = re.search(r"var VERSION = '([^']+)'", YTPLUS.read_text())
    return m.group(1) if m else "0"


def build_web(_args):
    header = f"""// ==UserScript==
// @name         YouTube +
// @namespace    https://github.com/mistermassacre/mutube
// @version      {version()}
// @description  Always show "Not interested" and "Don't recommend channel" in the long-press menu of every Home video tile on YouTube TV (youtube.com/tv).
// @match        https://www.youtube.com/tv*
// @match        https://youtube.com/tv*
// @icon         https://cdn.jsdelivr.net/gh/mistermassacre/mutube@youtube-plus/platforms/web/icons/icon-48.png
// @run-at       document-start
// @grant        none
// ==/UserScript==
// Generated by platforms/build_platforms.py from youtube-plus.js. Do not edit.
"""
    out = PLAT / "web" / "youtube-plus.user.js"
    out.write_text(header + YTPLUS.read_text())
    print("wrote", out.relative_to(ROOT))


def build_webos(args):
    out = BUILD / "webos"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(PLAT / "webos" / "app", out)
    for f in (PLAT / "webos" / "assets").iterdir():
        shutil.copy(f, out / f.name)
    parts = []
    if args.with_tizentube:
        parts.append(fetch(f"{TT_NPM}/dist/userScript.js").decode("utf-8"))
    parts.append(YTPLUS.read_text())
    # Re-open YouTube TV when the app is relaunched (deep link / voice), as youtube-webos does.
    parts.append("""
document.addEventListener('webOSRelaunch', function (evt) {
  var d = (evt && evt.detail) || {};
  var t = d.target || d.contentTarget;
  if (typeof t === 'string' && t.indexOf('v=') !== -1) {
    window.location.href = 'https://www.youtube.com/tv?' + t.replace(/^v=v=/, 'v=') + '#/';
  }
}, true);
""")
    us = out / "webOSUserScripts" / "userScript.js"
    us.parent.mkdir(parents=True, exist_ok=True)
    us.write_text("\n;\n".join(parts))
    info = json.loads((out / "appinfo.json").read_text())
    info["version"] = version()
    (out / "appinfo.json").write_text(json.dumps(info, indent=2) + "\n")
    print("wrote", out.relative_to(ROOT), "-> run: ares-package", out.relative_to(ROOT), "-o build")


def build_tizen_module(_args):
    dist = PLAT / "tizen" / "module" / "dist"
    dist.mkdir(parents=True, exist_ok=True)
    tt = fetch(f"{TT_NPM}/dist/userScript.js").decode("utf-8")
    service = fetch(f"{TT_NPM}/dist/service.js")
    # TizenTube first, YouTube + second: youtube-plus re-wraps JSON.parse so it
    # runs after TizenTube has rebuilt the tile menus.
    (dist / "userScript.js").write_text(
        f"/* TizenTube {TIZENTUBE_VERSION} (GPL-3.0, https://github.com/reisxd/TizenTube) + YouTube + {version()} */\n"
        + tt + "\n;\n" + YTPLUS.read_text())
    (dist / "service.js").write_bytes(service)
    pkg = PLAT / "tizen" / "module" / "package.json"
    data = json.loads(pkg.read_text())
    data["version"] = version()
    pkg.write_text(json.dumps(data, indent=2) + "\n")
    print("wrote", dist.relative_to(ROOT))


def build_tizen_standalone(args):
    if not args.tizentube_src:
        sys.exit("tizen-standalone needs --tizentube-src /path/to/TizenTube (git clone https://github.com/reisxd/TizenTube)")
    src = Path(args.tizentube_src) / "standalone"
    if not src.is_dir():
        sys.exit(f"{src} not found")
    out = BUILD / "tizen-standalone"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(src, out, ignore=shutil.ignore_patterns("node_modules"))
    shutil.copy(PLAT / "tizen" / "standalone" / "config.xml", out / "config.xml")
    for name in ("icon.png", "icon_16b9.png"):
        shutil.copy(PLAT / "tizen" / name, out / name)
    changed = []
    for f in list(out.rglob("*.js")) + list(out.rglob("*.html")):
        text = f.read_text(encoding="utf-8", errors="surrogateescape")
        new = TT_URL_RE.sub(args.bundle_url, text)
        if f.name == "index.html":
            new = re.sub(r">\s*TizenTube\s*<", ">YouTube +<", new)
        if new != text:
            f.write_text(new, encoding="utf-8", errors="surrogateescape")
            changed.append(str(f.relative_to(out)))
    print("patched:", ", ".join(changed) or "nothing (TizenTube layout changed?)")
    print("next: cd", out / "service", "&& npm install && node build-service.js; then package", out,
          "with Tizen Studio (or `tizen package -t wgt -s <cert-profile> -- " + str(out) + "`)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", choices=["web", "webos", "tizen-module", "tizen-standalone", "all"])
    ap.add_argument("--with-tizentube", action="store_true", help="webOS: also bundle TizenTube (experimental)")
    ap.add_argument("--tizentube-src", help="tizen-standalone: path to a TizenTube checkout")
    ap.add_argument("--bundle-url", default=TIZEN_BUNDLE_URL,
                    help="tizen-standalone: URL of the TizenTube+YouTube+ bundle the service injects")
    args = ap.parse_args()
    targets = ["web", "webos", "tizen-module"] if args.target == "all" else [args.target]
    for t in targets:
        print(f"[{t}]")
        {"web": build_web, "webos": build_webos, "tizen-module": build_tizen_module,
         "tizen-standalone": build_tizen_standalone}[t](args)


if __name__ == "__main__":
    main()
